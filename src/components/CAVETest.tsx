export default function CAVETest() {
  const [screen,   setScreen]   = useState("intro");
  const [currentQ, setCurrentQ] = useState(0);
  const [answers,  setAnswers]  = useState<Record<string, string[]>>({});

  const handleStart  = () => { setCurrentQ(0); setAnswers({}); setScreen("test"); };
  const handleRetry  = () => { setCurrentQ(0); setAnswers({}); setScreen("intro"); };

  const handleAnswer = (value: string) => {
    const q = QUESTIONS[currentQ];
    const newAnswers = { ...answers, [q.axis]: (answers[q.axis] || []).concat(value) };
    setAnswers(newAnswers);
    if (currentQ + 1 < QUESTIONS.length) {
      setCurrentQ(currentQ + 1);
    } else {
      setScreen("result");
    }
  };

  const calcResult = () => {
    const pick = (axis: string, a: string, b: string) => {
      const votes = answers[axis] || [];
      const aCount = votes.filter((v) => v === a).length;
      const bCount = votes.filter((v) => v === b).length;
      return aCount >= bCount ? a : b;
    };
    return pick("WA","W","A") + pick("FG","F","G") + pick("LR","L","R") + pick("DN","D","N");
  };

  if (screen === "intro") return <IntroScreen onStart={handleStart} />;
  if (screen === "test") {
    const q = QUESTIONS[currentQ];
    return (
      <TestScreen
        q={q} qNum={currentQ + 1} total={QUESTIONS.length}
        progress={(currentQ / QUESTIONS.length) * 100}
        stepInfo={STEP_INFO[q.step - 1]}
        stepProgress={STEP_INFO.map((s) => ({ ...s, done: q.step > s.step, active: q.step === s.step }))}
        onAnswer={handleAnswer}
      />
    );
  }
  if (screen === "result") {
    const code = calcResult();
    const type = TYPES[code];
    return <ResultScreen code={code} type={type} answers={answers} onRetry={handleRetry} />;
  }
  return null;
}

